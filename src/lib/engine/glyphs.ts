/** Stroke-only neon glyphs. Unit box ≈ [-1,1]; y-up. No fill. */

export type Stroke = [number, number][];

export interface Glyph {
  id: string;
  culture: string;
  strokes: Stroke[];
  rings?: number[];
  circles?: [number, number, number][];
  arcs?: [number, number, number, number, number][];
}

function R(...pairs: number[]): Stroke {
  const s: Stroke = [];
  for (let i = 0; i < pairs.length; i += 2) s.push([pairs[i]!, pairs[i + 1]!]);
  return s;
}

function poly(n: number, r: number, rot = Math.PI / 2): Stroke {
  const s: Stroke = [];
  for (let i = 0; i <= n; i++) {
    const a = rot + (i * 2 * Math.PI) / n;
    s.push([Math.cos(a) * r, Math.sin(a) * r]);
  }
  return s;
}

function star(n: number, ro: number, ri: number, rot = Math.PI / 2): Stroke {
  const s: Stroke = [];
  for (let i = 0; i <= n * 2; i++) {
    const r = i % 2 === 0 ? ro : ri;
    const a = rot + (i * Math.PI) / n;
    s.push([Math.cos(a) * r, Math.sin(a) * r]);
  }
  return s;
}

function rays(n: number, r0: number, r1: number, rot = 0): Stroke[] {
  const out: Stroke[] = [];
  for (let i = 0; i < n; i++) {
    const a = rot + (i * 2 * Math.PI) / n;
    out.push([
      [Math.cos(a) * r0, Math.sin(a) * r0],
      [Math.cos(a) * r1, Math.sin(a) * r1],
    ]);
  }
  return out;
}

function g(id: string, culture: string, strokes: Stroke[], extra: Partial<Glyph> = {}): Glyph {
  return { id, culture, strokes, ...extra };
}

function helmOfAwe(): Stroke[] {
  const s: Stroke[] = [];
  for (let i = 0; i < 8; i++) {
    const a = (i * Math.PI) / 4;
    const c = Math.cos(a);
    const si = Math.sin(a);
    const px = -si;
    const py = c;
    const p = (r: number): [number, number] => [c * r, si * r];
    s.push([p(0.12), p(0.98)]);
    s.push([
      [c * 0.58 + px * 0.3, si * 0.58 + py * 0.3],
      p(0.88),
      [c * 0.58 - px * 0.3, si * 0.58 - py * 0.3],
    ]);
    s.push([
      [c * 0.34 + px * 0.2, si * 0.34 + py * 0.2],
      p(0.56),
      [c * 0.34 - px * 0.2, si * 0.34 - py * 0.2],
    ]);
  }
  return s;
}

function vegvisir(): Stroke[] {
  const s: Stroke[] = [];
  for (let i = 0; i < 8; i++) {
    const a = (i * Math.PI) / 4;
    const c = Math.cos(a);
    const si = Math.sin(a);
    const px = -si;
    const py = c;
    const p = (r: number): [number, number] => [c * r, si * r];
    s.push([p(0.08), p(0.98)]);
    const k = i % 4;
    if (k === 0) {
      s.push([p(0.45), [c * 0.7 + px * 0.28, si * 0.7 + py * 0.28]]);
      s.push([p(0.45), [c * 0.7 - px * 0.28, si * 0.7 - py * 0.28]]);
      s.push([[c * 0.85 + px * 0.22, si * 0.85 + py * 0.22], p(0.98), [c * 0.85 - px * 0.22, si * 0.85 - py * 0.22]]);
    } else if (k === 1) {
      s.push([
        [c * 0.4 + px * 0.22, si * 0.4 + py * 0.22],
        p(0.62),
        [c * 0.4 - px * 0.22, si * 0.4 - py * 0.22],
      ]);
      s.push([[c * 0.75 + px * 0.18, si * 0.75 + py * 0.18], p(0.98)]);
    } else if (k === 2) {
      s.push([p(0.55), [c * 0.8 + px * 0.32, si * 0.8 + py * 0.32]]);
      s.push([p(0.55), [c * 0.8 - px * 0.32, si * 0.8 - py * 0.32]]);
    } else {
      s.push([
        [c * 0.5 + px * 0.26, si * 0.5 + py * 0.26],
        p(0.78),
        [c * 0.5 - px * 0.26, si * 0.5 - py * 0.26],
      ]);
    }
  }
  return s;
}

function chaosStar(): Stroke[] {
  const s: Stroke[] = rays(8, 0.2, 0.68);
  for (let i = 0; i < 8; i++) {
    const a = (i * Math.PI) / 4;
    const c = Math.cos(a);
    const si = Math.sin(a);
    const px = -si;
    const py = c;
    s.push([
      [c * 0.68 + px * 0.2, si * 0.68 + py * 0.2],
      [c * 0.98, si * 0.98],
      [c * 0.68 - px * 0.2, si * 0.68 - py * 0.2],
    ]);
  }
  return s;
}

function valknut(): Stroke[] {
  const offs: [number, number][] = [
    [0, 0.22],
    [-0.2, -0.14],
    [0.2, -0.14],
  ];
  return offs.map(([ox, oy]) => poly(3, 0.58, Math.PI / 2).map(([x, y]) => [x + ox, y + oy] as [number, number]));
}

function unicursal(): Stroke {
  const pts: [number, number][] = [
    [0, 1],
    [0.22, 0.18],
    [0.95, 0.18],
    [0.32, -0.18],
    [0.58, -0.95],
    [0, -0.38],
    [-0.58, -0.95],
    [-0.32, -0.18],
    [-0.95, 0.18],
    [-0.22, 0.18],
    [0, 1],
  ];
  return pts;
}

