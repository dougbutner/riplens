def _S(*xy: float) -> list[tuple[float, float]]:
    return list(zip(xy[0::2], xy[1::2]))


def _poly(n: int, r: float, rot: float = math.pi / 2) -> list[tuple[float, float]]:
    return [(math.cos(rot + i * 2 * math.pi / n) * r, math.sin(rot + i * 2 * math.pi / n) * r) for i in range(n + 1)]


def _star(n: int, ro: float, ri: float, rot: float = math.pi / 2) -> list[tuple[float, float]]:
    pts = []
    for i in range(n * 2 + 1):
        rad = ro if i % 2 == 0 else ri
        a = rot + i * math.pi / n
        pts.append((math.cos(a) * rad, math.sin(a) * rad))
    return pts


def _rays(n: int, r0: float, r1: float, rot: float = 0.0) -> list[list[tuple[float, float]]]:
    out = []
    for i in range(n):
        a = rot + i * 2 * math.pi / n
        out.append([(math.cos(a) * r0, math.sin(a) * r0), (math.cos(a) * r1, math.sin(a) * r1)])
    return out


def _g(gid: str, strokes, **extra):
    d = {"id": gid, "strokes": strokes}
    d.update(extra)
    return d


def _helm() -> list[list[tuple[float, float]]]:
    s = []
    for i in range(8):
        a = i * math.pi / 4
        c, si = math.cos(a), math.sin(a)
        px, py = -si, c

        def p(r, c=c, si=si):
            return (c * r, si * r)

        s.append([p(0.12), p(0.98)])
        s.append([(c * 0.58 + px * 0.3, si * 0.58 + py * 0.3), p(0.88), (c * 0.58 - px * 0.3, si * 0.58 - py * 0.3)])
        s.append([(c * 0.34 + px * 0.2, si * 0.34 + py * 0.2), p(0.56), (c * 0.34 - px * 0.2, si * 0.34 - py * 0.2)])
    return s


