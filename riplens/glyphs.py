def _xf(x: float, y: float, cx: float, cy: float, scale: float, rot: float) -> tuple[int, int]:
    c, s = math.cos(rot), math.sin(rot)
    xr, yr = x * c - y * s, x * s + y * c
    return int(cx + xr * scale), int(cy - yr * scale)


def _draw_glyph(img: np.ndarray, g: dict, cx: float, cy: float, scale: float, rot: float, color, thick: int) -> None:
    for stroke in g.get("strokes", []):
        if len(stroke) < 2:
            continue
        pts = np.array([_xf(px, py, cx, cy, scale, rot) for px, py in stroke], dtype=np.int32)
        cv2.polylines(img, [pts], False, color, thick, cv2.LINE_AA)
    for r in g.get("rings", []):
        p = _xf(0, 0, cx, cy, scale, rot)
        cv2.circle(img, p, max(2, int(r * scale)), color, thick, cv2.LINE_AA)
    for x, y, r in g.get("circles", []):
        p = _xf(x, y, cx, cy, scale, rot)
        cv2.circle(img, p, max(2, int(r * scale)), color, thick, cv2.LINE_AA)
    for x, y, r, a0, a1 in g.get("arcs", []):
        n = 20
        span = a1 - a0
        if abs(span) > math.pi * 1.8:
            # wrap the long way if needed
            pass
        pts = []
        for i in range(n + 1):
            a = a0 + span * i / n
            pts.append(_xf(x + math.cos(a) * r, y + math.sin(a) * r, cx, cy, scale, rot))
        cv2.polylines(img, [np.array(pts, dtype=np.int32)], False, color, thick, cv2.LINE_AA)


def overlay_glyphs(img: np.ndarray, feat: FrameFeat, t: float, solids_on: bool) -> np.ndarray:
    h, w = img.shape[:2]
    overlay = np.zeros_like(img)
    color = hsv_to_bgr(feat.h, min(1.0, feat.s + 0.25), 1.0)
    ring = min(w, h) * (0.42 if solids_on else 0.33)
    size = min(w, h) * (0.06 + feat.rms * 0.03)
    start = int(t * 0.72 + feat.bass * 8) % len(GLYPHS)
    cx, cy = w / 2, h / 2
    n = 8
    for i in range(n):
        g = GLYPHS[(start + i * 11) % len(GLYPHS)]
        a = t * 0.18 + i * 2 * math.pi / n
        _draw_glyph(overlay, g, cx + math.cos(a) * ring, cy + math.sin(a) * ring * 0.78, size, a + t * 0.4 + i, color, 2)
    if not solids_on:
        g = GLYPHS[(start + 17) % len(GLYPHS)]
        _draw_glyph(overlay, g, cx, cy - ring * 0.08, size * 1.45, t * 0.22, color, 2)
        for j in range(2):
            g2 = GLYPHS[(start + 23 + j * 13) % len(GLYPHS)]
            a = t * 0.55 + j * math.pi
            rr = ring * 0.16
            _draw_glyph(overlay, g2, cx + math.cos(a) * rr, cy + math.sin(a) * rr, size * 0.72, a, color, 2)
    halo = cv2.dilate(overlay, np.ones((3, 3), np.uint8))
    dark = np.clip(img.astype(np.int16) - (halo > 0).astype(np.int16) * 55, 0, 255).astype(np.uint8)
    return cv2.add(dark, overlay)


def overlay_solids(img: np.ndarray, feat: FrameFeat, t: float) -> np.ndarray:
    from riplens.effects import SOLID_CYCLE, _stroke_solid

    h, w = img.shape[:2]
    overlay = np.zeros_like(img)
    kind = SOLID_CYCLE[int(t * 0.38 + feat.bass * 2) % len(SOLID_CYCLE)]
    color = hsv_to_bgr(feat.h, min(1.0, feat.s + 0.15), 1.0)
    R = min(w, h) * (0.2 + feat.v * 0.08)
    _stroke_solid(overlay, kind, w / 2, h / 2, R, t * 0.7, t * 0.45, feat.bass, color, 2)
    halo = cv2.dilate(overlay, np.ones((3, 3), np.uint8))
    dark = np.clip(img.astype(np.int16) - (halo > 0).astype(np.int16) * 55, 0, 255).astype(np.uint8)
    return cv2.add(dark, overlay)
